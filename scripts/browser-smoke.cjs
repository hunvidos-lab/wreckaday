/* Run with API, worker, and Metro already running. Uses a separate test fixture
   story and deletes it. PLAYWRIGHT_CHROMIUM_PATH optionally selects system Chrome. */
const {chromium,expect}=require('@playwright/test');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_PATH?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_PATH}:{}),args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8081');
 await page.getByRole('button',{name:'View a sample',exact:true}).click();
 await expect(page.getByText('THE SAMPLE / NO ACCOUNT NEEDED')).toBeVisible();
 await page.getByRole('button',{name:'Make your own →'}).click();
 await page.getByLabel('FICTIONAL PROTAGONIST',{exact:true}).fill('Morgan');
 await page.getByRole('button',{name:'Sign in to generate →'}).click();
 await page.getByRole('button',{name:'Continue as Alex'}).click();
 await expect(page.getByLabel('FICTIONAL PROTAGONIST',{exact:true})).toHaveValue('Morgan');
 await page.getByRole('button',{name:'Review generation →'}).click();
 await page.getByRole('button',{name:'Confirm · generate for 3 demo credits'}).click();
 await page.waitForURL(/\/stories\/[^/]+\/edit/,{timeout:60000});
 const storyId=page.url().match(/stories\/([^/]+)/)[1];
 await expect(page.getByText('Make it worse.')).toBeVisible();
 await page.getByLabel(/CAPTION 1/).fill('Morgan made a questionable decision.');
 await page.getByRole('button',{name:'Move earlier ↑',exact:true}).last().click();
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await expect(page.getByRole('button',{name:'Render MP4 · free',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Render MP4 · free',exact:true}).click();
 await page.waitForURL(/\/jobs\//);
 await page.waitForURL(/\/stories\/[^/]+\/edit/,{timeout:60000});
 await expect(page.getByRole('button',{name:'Download MP4 ↓',exact:true})).toBeEnabled();
 fs.mkdirSync('work/browser',{recursive:true});
 await page.screenshot({path:'work/browser/editor-desktop.png'});
 const stillPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download this still ↓',exact:true}).first().click();
 const still=await stillPromise;await still.saveAs('work/browser/still.png');
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download MP4 ↓',exact:true}).click();
 const download=await downloadPromise;await download.saveAs('work/browser/story.mp4');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'work/browser/editor-mobile.png'});
 await page.getByRole('button',{name:'Delete story',exact:true}).click();
 await page.getByRole('button',{name:'Delete story and media',exact:true}).click();
 await page.waitForURL(/\/library/);
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Sign out & clear local cache',exact:true}).click();
 await page.waitForURL('http://localhost:8081/');
 await page.screenshot({path:'work/browser/welcome-mobile.png'});
 expect(errors).toEqual([]);
 console.log(JSON.stringify({passed:true,storyId,flow:'sample -> builder -> dev auth (draft preserved) -> generate -> edit/reorder -> export -> download -> delete -> logout',pageErrors:errors}));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
